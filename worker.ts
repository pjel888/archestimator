import {
  type CloudflareScheduledUploadJobEnv,
  runCloudflareScheduledUploadJobs,
} from "./src/lib/cloudflare/scheduled-upload-jobs";
import {
  type CloudflareUploadJobQueueBatchLike,
  type CloudflareUploadJobQueueEnv,
  runCloudflareUploadJobQueueBatch,
} from "./src/lib/cloudflare/upload-job-queue";
import {
  type CloudflareCollaborationRoomEnv,
  routeCollaborationRoomRequest,
} from "./src/lib/cloudflare/collaboration-room-router";
import {
  type CloudflareProtectedProofEnv,
  routeCloudflareProtectedProofRequest,
} from "./src/lib/cloudflare/protected-proof-routes";
import {
  routeCloudflareFastHealthRequest,
  routeMalformedShareTokenRequest,
  routeStaticPublicPageThroughCache,
} from "./src/lib/cloudflare/worker-route-optimizations";

// Generated by `bun run cf:build` before Wrangler builds or previews this worker.
// @ts-ignore
import generatedOpenNextWorker from "./.open-next/worker.js";

// Preserve OpenNext-generated Durable Object exports while wrapping the fetch handler.
// @ts-ignore
export { BucketCachePurge, DOQueueHandler, DOShardedTagCache } from "./.open-next/worker.js";
export { CollaborationRoom } from "./src/lib/cloudflare/collaboration-room";

type CloudflareWorkerEnv = Record<string, unknown>
  & CloudflareScheduledUploadJobEnv
  & CloudflareUploadJobQueueEnv
  & CloudflareCollaborationRoomEnv
  & CloudflareProtectedProofEnv;

type ExecutionContextLike = {
  waitUntil(promise: Promise<unknown>): void;
};

type ScheduledControllerLike = {
  cron: string;
};

type OpenNextWorker = {
  fetch(request: Request, env: CloudflareWorkerEnv, ctx: ExecutionContextLike): Promise<Response> | Response;
};

const openNextWorker = generatedOpenNextWorker as OpenNextWorker;

export default {
  async fetch(request: Request, env: CloudflareWorkerEnv, ctx: ExecutionContextLike) {
    const fastHealthResponse = routeCloudflareFastHealthRequest(request);
    if (fastHealthResponse) return fastHealthResponse;

    const malformedShareTokenResponse = routeMalformedShareTokenRequest(request);
    if (malformedShareTokenResponse) return malformedShareTokenResponse;

    const proofResponse = await routeCloudflareProtectedProofRequest(request, env);
    if (proofResponse) return proofResponse;

    const collaborationRoomResponse = await routeCollaborationRoomRequest(request, env);
    if (collaborationRoomResponse) return collaborationRoomResponse;

    const cachedPublicPageResponse = await routeStaticPublicPageThroughCache(
      request,
      ctx,
      (publicPageRequest) => openNextWorker.fetch(publicPageRequest, env, ctx),
    );
    if (cachedPublicPageResponse) return cachedPublicPageResponse;

    return openNextWorker.fetch(request, env, ctx);
  },

  scheduled(controller: ScheduledControllerLike, env: CloudflareWorkerEnv, ctx: ExecutionContextLike) {
    ctx.waitUntil(
      runCloudflareScheduledUploadJobs({
        cron: controller.cron,
        env,
        fetcher: (request) => openNextWorker.fetch(request, env, ctx),
      }).then((summary) => {
        console.log("Cloudflare scheduled upload jobs completed", JSON.stringify(summary));
      }),
    );
  },

  queue(batch: CloudflareUploadJobQueueBatchLike, env: CloudflareWorkerEnv, ctx: ExecutionContextLike) {
    ctx.waitUntil(
      runCloudflareUploadJobQueueBatch({
        batch,
        env,
        fetcher: (request) => openNextWorker.fetch(request, env, ctx),
      }).then((summary) => {
        console.log("Cloudflare upload job queue batch completed", JSON.stringify(summary));
      }),
    );
  },
};
