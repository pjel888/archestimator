const FLOW_DEFINITIONS = new Map<OnboardingFlowKey, OnboardingFlowDefinition>(
  ONBOARDING_FLOW_CATALOG.map((definition) => [definition.key, definition]),
);

export function getOnboardingFlowDefinition(
  flowKey: OnboardingFlowKey,
): OnboardingFlowDefinition {
  const definition = FLOW_DEFINITIONS.get(flowKey);
  if (!definition) {
    throw new Error(`Unknown onboarding flow: ${flowKey}`);
  }
  return definition;
}
