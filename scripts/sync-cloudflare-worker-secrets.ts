#!/usr/bin/env bun

import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

import { DEPLOYED_WORKER_SECRET_NAMES } from "./check-cloudflare-worker-readiness";

const PLAN_ROOT = ".ai/03_plans/2026-06-29-Cloudflare-Migration-Codex/evidence";
const DEFAULT_OUTPUT_FILE = `${PLAN_ROOT}/2026-06-30-cloudflare-worker-secret-sync.json`;
const DEFAULT_MARKDOWN_FILE = `${PLAN_ROOT}/2026-06-30-cloudflare-worker-secret-sync.md`;
const DEFAULT_ENV_FILES = [".env.local", ".dev.vars"] as const;
const DEFAULT_GENERATED_SECRET_NAMES = [
  "CRON_SECRET",
  "UPLOAD_CLEANUP_JOB_SECRET",
  "UPLOAD_SCAN_JOB_SECRET",
] as const;

type SecretInputValue = {
  name: string;
  value: string;
  source: string;
};

export type SecretInputStatus = {
  name: string;
  present: boolean;
  source: string | null;
};

export type SecretUploadCommandResult = {
  name: string;
  args: string[];
  skipped: boolean;
  exitCode: number | null;
  signal: string | null;
  timedOut: boolean;
  stdoutBytes: number;
  stderrBytes: number;
  ready: boolean;
};

export type SecretListReadback = {
  checked: boolean;
  exitCode: number | null;
  signal: string | null;
  timedOut: boolean;
  stdoutBytes: number;
  stderrBytes: number;
  foundNames: string[];
  missingNames: string[];
  ready: boolean;
};

export type CloudflareWorkerSecretSyncReport = {
  generatedAt: string;
  mode: "cloudflare-worker-secret-sync";
  workerName: string;
  dryRun: boolean;
  envFiles: string[];
  generatedMissingNames: string[];
  defaultedMissingNames: string[];
  requiredSecretNames: string[];
  inputs: SecretInputStatus[];
  uploadCommands: SecretUploadCommandResult[];
  secretListReadback: SecretListReadback;
  readiness: {
    inputsReady: boolean;
    uploadAttempted: boolean;
    uploadedSecretNamesReady: boolean;
    productionCutoverReady: boolean;
  };
  blockers: string[];
  note: string;
};

type CommandRunner = (input: {
  name: string;
  value: string;
  workerName: string;
}) => SecretUploadCommandResult;

type SecretListRunner = (input: {
  workerName: string;
  requiredNames: string[];
}) => SecretListReadback;

function readEnv(name: string) {
  const value = process.env[name];
  return value?.trim() || undefined;
}

function unique(values: string[]) {
  return [...new Set(values.map((value) => value.trim()).filter(Boolean))].sort();
}

function unquoteEnvValue(value: string) {
  const trimmed = value.trim();
  const quote = trimmed[0];
  if ((quote === "\"" || quote === "'") && trimmed.endsWith(quote)) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

export function parseEnvAssignments(input: string, source: string): SecretInputValue[] {
  const values: SecretInputValue[] = [];
  for (const line of input.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const match = trimmed.match(/^(?:export\s+)?([A-Z][A-Z0-9_]+)\s*=\s*(.*)$/);
    if (!match) continue;
    values.push({
      name: match[1],
      value: unquoteEnvValue(match[2]),
      source,
    });
  }
  return values;
}

export function loadSecretInputs(envFiles: string[]): Map<string, SecretInputValue> {
  const values = new Map<string, SecretInputValue>();
  for (const file of envFiles) {
    if (!existsSync(file)) continue;
    for (const assignment of parseEnvAssignments(readFileSync(file, "utf8"), file)) {
      if (!assignment.value.trim()) continue;
      if (!values.has(assignment.name)) values.set(assignment.name, assignment);
    }
  }
  return values;
}

function randomSecret() {
  return randomBytes(48).toString("base64url");
}

export function writeGeneratedMissingSecrets(input: {
  envFile: string;
  missingNames: string[];
  generatedNames?: readonly string[];
  generatedAt?: string;
}) {
  const allowed = new Set(input.generatedNames ?? DEFAULT_GENERATED_SECRET_NAMES);
  const names = input.missingNames.filter((name) => allowed.has(name));
  if (names.length === 0) return [];
  const generatedAt = input.generatedAt ?? new Date().toISOString();
  const lines = [
    "",
    `# Generated by cf:sync-worker-secrets on ${generatedAt}. Never commit real secret values.`,
    ...names.map((name) => `${name}=${randomSecret()}`),
    "",
  ];
  appendFileSync(input.envFile, lines.join("\n"));
  return names;
}

function proofDefaults(baseUrl: string | null) {
  const entries: Array<[string, string]> = [
    ["ARCHESTIMATOR_AI_ENABLED", "false"],
    ["CLOSED_BETA_ACCESS_ENABLED", "false"],
    ["NEXT_PUBLIC_ASK_FLIP_UI_ENABLED", "false"],
    ...(baseUrl
      ? [
          ["ARCHESTIMATOR_ALLOWED_APP_ORIGINS", baseUrl] as [string, string],
          ["NEXT_PUBLIC_APP_URL", baseUrl] as [string, string],
          ["NEXT_PUBLIC_SITE_URL", baseUrl] as [string, string],
        ]
      : []),
  ];
  return new Map(entries);
}

export function writeProofDefaultMissingSecrets(input: {
  envFile: string;
  missingNames: string[];
  proofBaseUrl?: string | null;
  generatedAt?: string;
}) {
  const defaults = proofDefaults(input.proofBaseUrl ?? null);
  const names = input.missingNames.filter((name) => defaults.has(name));
  if (names.length === 0) return [];
  const generatedAt = input.generatedAt ?? new Date().toISOString();
  const lines = [
    "",
    `# Proof defaults written by cf:sync-worker-secrets on ${generatedAt}. Review before production cutover.`,
    ...names.map((name) => `${name}=${defaults.get(name)}`),
    "",
  ];
  appendFileSync(input.envFile, lines.join("\n"));
  return names;
}

function skippedUpload(name: string, workerName: string, reasonReady = true): SecretUploadCommandResult {
  return {
    name,
    args: ["wrangler", "secret", "put", name, "--name", workerName],
    skipped: true,
    exitCode: null,
    signal: null,
    timedOut: false,
    stdoutBytes: 0,
    stderrBytes: 0,
    ready: reasonReady,
  };
}

function runWranglerSecretPut(input: { name: string; value: string; workerName: string }): SecretUploadCommandResult {
  const args = ["wrangler", "secret", "put", input.name, "--name", input.workerName];
  const result = spawnSync("bunx", args, {
    input: `${input.value}\n`,
    encoding: "utf8",
    timeout: 60_000,
    maxBuffer: 1024 * 1024,
  });
  return {
    name: input.name,
    args,
    skipped: false,
    exitCode: result.status,
    signal: result.signal,
    timedOut: result.error?.message.includes("ETIMEDOUT") ?? false,
    stdoutBytes: Buffer.byteLength(result.stdout ?? ""),
    stderrBytes: Buffer.byteLength(result.stderr ?? ""),
    ready: result.status === 0 && !result.error,
  };
}

export function extractCloudflareSecretListNames(input: string) {
  const trimmed = input.trim();
  if (!trimmed) return [];
  try {
    const parsed = JSON.parse(trimmed) as unknown;
    if (!Array.isArray(parsed)) return [];
    return unique(parsed.flatMap((item) => {
      if (!item || typeof item !== "object") return [];
      const record = item as Record<string, unknown>;
      return typeof record.name === "string" ? [record.name] : [];
    }));
  } catch {
    return unique(trimmed.match(/\b[A-Z][A-Z0-9]+(?:_[A-Z0-9]+)+\b/g) ?? []);
  }
}

function runWranglerSecretList(input: { workerName: string; requiredNames: string[] }): SecretListReadback {
  const result = spawnSync("bunx", ["wrangler", "secret", "list", "--name", input.workerName, "--format", "json"], {
    encoding: "utf8",
    timeout: 30_000,
    maxBuffer: 1024 * 1024,
  });
  const foundNames = extractCloudflareSecretListNames(result.stdout ?? "");
  const missingNames = input.requiredNames.filter((name) => !foundNames.includes(name));
  return {
    checked: true,
    exitCode: result.status,
    signal: result.signal,
    timedOut: result.error?.message.includes("ETIMEDOUT") ?? false,
    stdoutBytes: Buffer.byteLength(result.stdout ?? ""),
    stderrBytes: Buffer.byteLength(result.stderr ?? ""),
    foundNames,
    missingNames,
    ready: result.status === 0 && !result.error && missingNames.length === 0,
  };
}

function skippedSecretList(requiredNames: string[]): SecretListReadback {
  return {
    checked: false,
    exitCode: null,
    signal: null,
    timedOut: false,
    stdoutBytes: 0,
    stderrBytes: 0,
    foundNames: [],
    missingNames: requiredNames,
    ready: false,
  };
}

export function buildCloudflareWorkerSecretSyncReport(input: {
  envFiles: string[];
  workerName: string;
  apply?: boolean;
  generatedMissingNames?: string[];
  defaultedMissingNames?: string[];
  requiredSecretNames?: readonly string[];
  commandRunner?: CommandRunner;
  secretListRunner?: SecretListRunner;
  generatedAt?: string;
}): CloudflareWorkerSecretSyncReport {
  const requiredSecretNames = [...(input.requiredSecretNames ?? DEPLOYED_WORKER_SECRET_NAMES)].sort();
  const values = loadSecretInputs(input.envFiles);
  const inputs = requiredSecretNames.map<SecretInputStatus>((name) => {
    const value = values.get(name);
    return {
      name,
      present: Boolean(value),
      source: value?.source ?? null,
    };
  });
  const missingNames = inputs.filter((item) => !item.present).map((item) => item.name);
  const inputsReady = missingNames.length === 0;
  const apply = input.apply === true;
  const commandRunner = input.commandRunner ?? runWranglerSecretPut;
  const secretListRunner = input.secretListRunner ?? runWranglerSecretList;
  const uploadCommands = apply && inputsReady
    ? requiredSecretNames.map((name) => {
        const value = values.get(name);
        if (!value) return skippedUpload(name, input.workerName, false);
        return commandRunner({
          name,
          value: value.value,
          workerName: input.workerName,
        });
      })
    : requiredSecretNames.map((name) => skippedUpload(name, input.workerName, !apply));
  const uploadAttempted = uploadCommands.some((command) => !command.skipped);
  const uploadSucceeded = uploadAttempted && uploadCommands.every((command) => command.ready);
  const secretListReadback = uploadSucceeded
    ? secretListRunner({ workerName: input.workerName, requiredNames: requiredSecretNames })
    : skippedSecretList(requiredSecretNames);
  const blockers: string[] = [];
  if (!inputsReady) {
    blockers.push(`Missing non-empty local inputs for Worker secrets: ${missingNames.join(", ")}.`);
  }
  if (apply && inputsReady && !uploadSucceeded) {
    const failed = uploadCommands.filter((command) => !command.ready).map((command) => command.name);
    blockers.push(`One or more Wrangler secret uploads failed: ${failed.join(", ")}.`);
  }
  if (apply && uploadSucceeded && !secretListReadback.ready) {
    blockers.push(`Worker secret-list readback is incomplete: ${secretListReadback.missingNames.join(", ")}.`);
  }

  return {
    generatedAt: input.generatedAt ?? new Date().toISOString(),
    mode: "cloudflare-worker-secret-sync",
    workerName: input.workerName,
    dryRun: !apply,
    envFiles: input.envFiles,
    generatedMissingNames: input.generatedMissingNames ?? [],
    defaultedMissingNames: input.defaultedMissingNames ?? [],
    requiredSecretNames,
    inputs,
    uploadCommands,
    secretListReadback,
    readiness: {
      inputsReady,
      uploadAttempted,
      uploadedSecretNamesReady: secretListReadback.ready,
      productionCutoverReady: false,
    },
    blockers,
    note: "Preflights or uploads Cloudflare Worker secrets through Wrangler without printing secret values. Dry-run is the default. Apply mode passes values through stdin, records only names/status/byte counts, and does not deploy Workers, change DNS, purchase plans, delete resources, or make production cutover ready.",
  };
}

export function writeOutput(outputFile: string, report: CloudflareWorkerSecretSyncReport) {
  const resolved = resolve(outputFile);
  mkdirSync(dirname(resolved), { recursive: true });
  writeFileSync(resolved, `${JSON.stringify(report, null, 2)}\n`);
}

export function writeMarkdown(report: CloudflareWorkerSecretSyncReport, markdownFile: string) {
  const resolved = resolve(markdownFile);
  mkdirSync(dirname(resolved), { recursive: true });
  const inputRows = report.inputs.map((input) => [
    input.name,
    input.present ? "present" : "missing",
    input.source ?? "(none)",
  ]);
  const commandRows = report.uploadCommands.map((command) => [
    command.name,
    command.skipped ? "SKIPPED" : command.ready ? "PASS" : "FAIL",
    command.exitCode === null ? "(none)" : String(command.exitCode),
    String(command.stdoutBytes),
    String(command.stderrBytes),
  ]);
  const blockers = report.blockers.length > 0 ? report.blockers.map((blocker) => `- ${blocker}`) : ["- (none)"];
  const lines = [
    "# Cloudflare Worker Secret Sync",
    "",
    `Generated: ${report.generatedAt}`,
    `Worker: ${report.workerName}`,
    `Dry run: ${report.dryRun ? "yes" : "no"}`,
    `Inputs ready: ${report.readiness.inputsReady ? "yes" : "no"}`,
    `Upload attempted: ${report.readiness.uploadAttempted ? "yes" : "no"}`,
    `Uploaded secret names ready: ${report.readiness.uploadedSecretNamesReady ? "yes" : "no"}`,
    `Production cutover ready: ${report.readiness.productionCutoverReady ? "yes" : "no"}`,
    "",
    report.note,
    "",
    `Generated local-only missing names: ${report.generatedMissingNames.join(", ") || "(none)"}`,
    `Defaulted proof missing names: ${report.defaultedMissingNames.join(", ") || "(none)"}`,
    "",
    "## Inputs",
    "",
    "| Secret name | Status | Source |",
    "| --- | --- | --- |",
    ...inputRows.map((row) => `| ${row.join(" | ")} |`),
    "",
    "## Upload Commands",
    "",
    "| Secret name | Result | Exit | Stdout bytes | Stderr bytes |",
    "| --- | --- | ---: | ---: | ---: |",
    ...commandRows.map((row) => `| ${row.join(" | ")} |`),
    "",
    "## Secret List Readback",
    "",
    `- Checked: ${report.secretListReadback.checked ? "yes" : "no"}`,
    `- Found names: ${report.secretListReadback.foundNames.join(", ") || "(none)"}`,
    `- Missing names: ${report.secretListReadback.missingNames.join(", ") || "(none)"}`,
    "",
    "## Blockers",
    "",
    ...blockers,
    "",
  ];
  writeFileSync(resolved, lines.join("\n"));
}

function parseArgs(argv: string[]) {
  const result: {
    apply: boolean;
    writeGeneratedMissing: boolean;
    writeProofDefaults: boolean;
    proofBaseUrl: string | null;
    envFiles: string[];
    workerName: string | null;
    outputFile: string;
    markdownFile: string;
  } = {
    apply: readEnv("CLOUDFLARE_WORKER_SECRET_SYNC_APPLY") === "1",
    writeGeneratedMissing: readEnv("CLOUDFLARE_WORKER_SECRET_WRITE_GENERATED_MISSING") === "1",
    writeProofDefaults: readEnv("CLOUDFLARE_WORKER_SECRET_WRITE_PROOF_DEFAULTS") === "1",
    proofBaseUrl: readEnv("CLOUDFLARE_WORKER_PROOF_BASE_URL") ?? null,
    envFiles: (readEnv("CLOUDFLARE_WORKER_SECRET_ENV_FILES")?.split(",").map((item) => item.trim()).filter(Boolean)
      ?? [...DEFAULT_ENV_FILES]),
    workerName: readEnv("CLOUDFLARE_WORKER_NAME") ?? null,
    outputFile: readEnv("OUTPUT_FILE") ?? DEFAULT_OUTPUT_FILE,
    markdownFile: readEnv("MARKDOWN_FILE") ?? DEFAULT_MARKDOWN_FILE,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--apply") result.apply = true;
    else if (arg === "--dry-run") result.apply = false;
    else if (arg === "--write-generated-missing") result.writeGeneratedMissing = true;
    else if (arg === "--write-proof-defaults") result.writeProofDefaults = true;
    else if (arg === "--proof-base-url") result.proofBaseUrl = argv[++index];
    else if (arg === "--env-file") result.envFiles.push(argv[++index]);
    else if (arg === "--worker-name") result.workerName = argv[++index];
    else if (arg === "--output") result.outputFile = argv[++index];
    else if (arg === "--markdown") result.markdownFile = argv[++index];
  }

  return result;
}

function readWorkerName() {
  try {
    const raw = readFileSync("wrangler.jsonc", "utf8");
    const withoutLineComments = raw.replace(/(^|\s+)\/\/.*$/gm, "$1");
    const parsed = JSON.parse(withoutLineComments) as { name?: string };
    return parsed.name ?? "archestimator-proof";
  } catch {
    return "archestimator-proof";
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const workerName = args.workerName ?? readWorkerName();
  let generatedMissingNames: string[] = [];
  let defaultedMissingNames: string[] = [];
  if (args.writeProofDefaults) {
    const currentValues = loadSecretInputs(args.envFiles);
    const missingNames = [...DEPLOYED_WORKER_SECRET_NAMES].filter((name) => !currentValues.has(name));
    const targetFile = args.envFiles[0] ?? ".env.local";
    defaultedMissingNames = writeProofDefaultMissingSecrets({
      envFile: targetFile,
      missingNames,
      proofBaseUrl: args.proofBaseUrl,
    });
  }
  if (args.writeGeneratedMissing) {
    const currentValues = loadSecretInputs(args.envFiles);
    const missingNames = [...DEPLOYED_WORKER_SECRET_NAMES].filter((name) => !currentValues.has(name));
    const targetFile = args.envFiles[0] ?? ".env.local";
    generatedMissingNames = writeGeneratedMissingSecrets({ envFile: targetFile, missingNames });
  }
  const report = buildCloudflareWorkerSecretSyncReport({
    envFiles: args.envFiles,
    workerName,
    apply: args.apply,
    generatedMissingNames,
    defaultedMissingNames,
  });
  writeOutput(args.outputFile, report);
  writeMarkdown(report, args.markdownFile);
  console.log(JSON.stringify(report, null, 2));
  if (args.apply && !report.readiness.uploadedSecretNamesReady) process.exitCode = 1;
}

if (import.meta.main) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
