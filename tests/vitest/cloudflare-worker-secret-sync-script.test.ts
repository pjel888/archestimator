import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import {
  buildCloudflareWorkerSecretSyncReport,
  extractCloudflareSecretListNames,
  parseEnvAssignments,
  writeGeneratedMissingSecrets,
  writeProofDefaultMissingSecrets,
  writeMarkdown,
} from "../../scripts/sync-cloudflare-worker-secrets";

const REQUIRED_NAMES = [
  "CRON_SECRET",
  "PUBLICATION_TOKEN_HASH_SECRET",
] as const;

describe("Cloudflare Worker secret sync helper", () => {
  it("parses env assignments without exposing values in reports", () => {
    const parsed = parseEnvAssignments("CRON_SECRET=very-secret\nEMPTY_SECRET=\n", ".env.local");

    expect(parsed).toEqual([
      { name: "CRON_SECRET", value: "very-secret", source: ".env.local" },
      { name: "EMPTY_SECRET", value: "", source: ".env.local" },
    ]);
  });

  it("dry-runs by default and reports only secret names and sources", () => {
    const dir = mkdtempSync(join(tmpdir(), "cloudflare-secret-sync-"));
    try {
      const envFile = join(dir, ".env.local");
      writeFileSync(envFile, "PUBLICATION_TOKEN_HASH_SECRET=do-not-leak\n");
      const report = buildCloudflareWorkerSecretSyncReport({
        envFiles: [envFile],
        workerName: "archestimator-proof",
        requiredSecretNames: REQUIRED_NAMES,
        generatedAt: "2026-06-30T00:00:00.000Z",
      });

      expect(report.dryRun).toBe(true);
      expect(report.readiness.inputsReady).toBe(false);
      expect(report.inputs).toContainEqual({
        name: "PUBLICATION_TOKEN_HASH_SECRET",
        present: true,
        source: envFile,
      });
      expect(JSON.stringify(report)).not.toContain("do-not-leak");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("can append generated local-only missing secrets without returning values", () => {
    const dir = mkdtempSync(join(tmpdir(), "cloudflare-secret-generate-"));
    try {
      const envFile = join(dir, ".env.local");
      writeFileSync(envFile, "PUBLICATION_TOKEN_HASH_SECRET=existing\n");
      const generated = writeGeneratedMissingSecrets({
        envFile,
        missingNames: ["CRON_SECRET", "PUBLICATION_TOKEN_HASH_SECRET"],
        generatedNames: ["CRON_SECRET"],
        generatedAt: "2026-06-30T00:00:00.000Z",
      });
      const text = readFileSync(envFile, "utf8");

      expect(generated).toEqual(["CRON_SECRET"]);
      expect(text).toContain("CRON_SECRET=");
      expect(text).toContain("Generated by cf:sync-worker-secrets");
      expect(generated.join("\n")).not.toContain("=");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("can append proof defaults from a hosted Worker URL", () => {
    const dir = mkdtempSync(join(tmpdir(), "cloudflare-secret-defaults-"));
    try {
      const envFile = join(dir, ".env.local");
      writeFileSync(envFile, "");
      const defaulted = writeProofDefaultMissingSecrets({
        envFile,
        missingNames: [
          "NEXT_PUBLIC_APP_URL",
          "NEXT_PUBLIC_SITE_URL",
          "ARCHESTIMATOR_ALLOWED_APP_ORIGINS",
          "BETTER_AUTH_URL",
          "BETTER_AUTH_TRUSTED_ORIGINS",
          "ARCHESTIMATOR_AI_ENABLED",
          "CLOSED_BETA_ACCESS_ENABLED",
        ],
        proofBaseUrl: "https://archestimator-proof.example.workers.dev",
        generatedAt: "2026-06-30T00:00:00.000Z",
      });
      const text = readFileSync(envFile, "utf8");

      expect(defaulted).toEqual([
        "NEXT_PUBLIC_APP_URL",
        "NEXT_PUBLIC_SITE_URL",
        "ARCHESTIMATOR_ALLOWED_APP_ORIGINS",
        "BETTER_AUTH_URL",
        "BETTER_AUTH_TRUSTED_ORIGINS",
        "ARCHESTIMATOR_AI_ENABLED",
        "CLOSED_BETA_ACCESS_ENABLED",
      ]);
      expect(text).toContain("NEXT_PUBLIC_APP_URL=https://archestimator-proof.example.workers.dev");
      expect(text).toContain("BETTER_AUTH_URL=https://archestimator-proof.example.workers.dev");
      expect(text).toContain("ARCHESTIMATOR_AI_ENABLED=false");
      expect(text).toContain("CLOSED_BETA_ACCESS_ENABLED=true");
      expect(defaulted.join("\n")).not.toContain("https://");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("apply mode passes values only to the command runner and records sanitized status", () => {
    const dir = mkdtempSync(join(tmpdir(), "cloudflare-secret-apply-"));
    try {
      const envFile = join(dir, ".env.local");
      writeFileSync(envFile, "CRON_SECRET=secret-one\nPUBLICATION_TOKEN_HASH_SECRET=secret-two\n");
      const seenValues: string[] = [];
      const report = buildCloudflareWorkerSecretSyncReport({
        envFiles: [envFile],
        workerName: "archestimator-proof",
        requiredSecretNames: REQUIRED_NAMES,
        apply: true,
        generatedAt: "2026-06-30T00:00:00.000Z",
        commandRunner: ({ name, value, workerName }) => {
          seenValues.push(value);
          return {
            name,
            args: ["wrangler", "secret", "put", name, "--name", workerName],
            skipped: false,
            exitCode: 0,
            signal: null,
            timedOut: false,
            stdoutBytes: 20,
            stderrBytes: 0,
            ready: true,
          };
        },
        secretListRunner: ({ requiredNames }) => ({
          checked: true,
          exitCode: 0,
          signal: null,
          timedOut: false,
          stdoutBytes: 120,
          stderrBytes: 0,
          foundNames: [...requiredNames],
          missingNames: [],
          ready: true,
        }),
      });

      expect(seenValues).toEqual(["secret-one", "secret-two"]);
      expect(report.readiness.uploadAttempted).toBe(true);
      expect(report.readiness.uploadedSecretNamesReady).toBe(true);
      expect(JSON.stringify(report)).not.toContain("secret-one");
      expect(JSON.stringify(report)).not.toContain("secret-two");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("extracts secret names from Wrangler list JSON and writes redacted markdown", () => {
    expect(extractCloudflareSecretListNames(JSON.stringify([{ name: "CRON_SECRET" }]))).toEqual(["CRON_SECRET"]);
    const dir = mkdtempSync(join(tmpdir(), "cloudflare-secret-markdown-"));
    try {
      const file = join(dir, "secret-sync.md");
      const report = buildCloudflareWorkerSecretSyncReport({
        envFiles: [],
        workerName: "archestimator-proof",
        requiredSecretNames: REQUIRED_NAMES,
        generatedAt: "2026-06-30T00:00:00.000Z",
      });
      writeMarkdown(report, file);
      const markdown = readFileSync(file, "utf8");

      expect(markdown).toContain("Cloudflare Worker Secret Sync");
      expect(markdown).toContain("CRON_SECRET");
      expect(markdown).not.toContain("very-secret");
      expect(markdown).not.toContain("Authorization: Bearer");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
