import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

import { describe, expect, it } from "vitest";

import { generateLocalBetterAuthD1SchemaSqlProof } from "../../scripts/generate-cloudflare-better-auth-proof";

const requireRuntime = createRequire(import.meta.url);
const rateLimitMigration = readFileSync("migrations/0041_better_auth_rate_limit.sql", "utf8");
const coreSchemaMigration = readFileSync("migrations/0104_better_auth_core_schema.sql", "utf8");
const tableNames = ["user", "session", "account", "verification", "rateLimit"] as const;
const namedIndexNames = [
  "account_userId_idx",
  "rateLimit_key_idx",
  "session_userId_idx",
  "verification_identifier_idx",
] as const;

type LocalSqliteDatabase = {
  exec(sql: string): void;
  prepare(sql: string): {
    all(...parameters: unknown[]): Record<string, unknown>[];
    get(...parameters: unknown[]): Record<string, unknown> | undefined;
    run(...parameters: unknown[]): unknown;
  };
  close(): void;
};

function createDatabase() {
  const { DatabaseSync } = requireRuntime("node:sqlite") as {
    DatabaseSync: new (path: string) => LocalSqliteDatabase;
  };
  const database = new DatabaseSync(":memory:");
  database.exec("PRAGMA foreign_keys = ON;");
  return database;
}

function quoteIdentifier(value: string) {
  return `"${value.replaceAll('"', '""')}"`;
}

function schemaDescriptor(database: LocalSqliteDatabase) {
  return {
    tables: Object.fromEntries(tableNames.map((tableName) => [
      tableName,
      {
        columns: database.prepare(`PRAGMA table_info(${quoteIdentifier(tableName)})`).all()
          .map((column) => ({
            ...column,
            type: String(column.type).toLowerCase() === "bigint"
              ? "integer"
              : String(column.type).toLowerCase(),
          })),
        foreignKeys: database.prepare(`PRAGMA foreign_key_list(${quoteIdentifier(tableName)})`).all(),
        indexes: database.prepare(`PRAGMA index_list(${quoteIdentifier(tableName)})`).all()
          .filter((index) => index.name !== "rateLimit_key_idx")
          .map((index) => ({
            name: index.name,
            unique: index.unique,
            columns: database.prepare(`PRAGMA index_info(${quoteIdentifier(String(index.name))})`).all()
              .map((column) => column.name),
          }))
          .sort((left, right) => String(left.name).localeCompare(String(right.name))),
      },
    ])),
    namedIndexes: database.prepare(`
      SELECT name, tbl_name
      FROM sqlite_master
      WHERE type = 'index'
        AND name NOT LIKE 'sqlite_autoindex_%'
        AND name != 'rateLimit_key_idx'
      ORDER BY name
    `).all(),
  };
}

function applyTrackedSchema(database: LocalSqliteDatabase) {
  database.exec(rateLimitMigration);
  database.exec(coreSchemaMigration);
}

describe("Better Auth core D1 schema migration", () => {
  it("matches the schema generated by pinned Better Auth", async () => {
    const proof = await generateLocalBetterAuthD1SchemaSqlProof();
    expect(proof.generated).toBe(true);
    expect(proof.sql).toBeTruthy();

    const generated = createDatabase();
    const tracked = createDatabase();
    try {
      generated.exec(proof.sql);
      applyTrackedSchema(tracked);

      expect(schemaDescriptor(tracked)).toEqual(schemaDescriptor(generated));
      expect(tracked.prepare(`
        SELECT name
        FROM sqlite_master
        WHERE type = 'index' AND name IN (${namedIndexNames.map(() => "?").join(", ")})
        ORDER BY name
      `).all(...namedIndexNames).map((row) => row.name)).toEqual([...namedIndexNames].sort());
      expect(tracked.prepare("PRAGMA foreign_key_check").all()).toEqual([]);
    } finally {
      generated.close();
      tracked.close();
    }
  });

  it("is idempotent and preserves a compatible partially provisioned schema", () => {
    const database = createDatabase();
    try {
      database.exec(rateLimitMigration);
      database.exec(`
        CREATE TABLE "user" (
          "id" TEXT NOT NULL PRIMARY KEY,
          "name" TEXT NOT NULL,
          "email" TEXT NOT NULL UNIQUE,
          "emailVerified" INTEGER NOT NULL,
          "image" TEXT,
          "createdAt" DATE NOT NULL,
          "updatedAt" DATE NOT NULL
        );
        INSERT INTO "user" (
          "id", "name", "email", "emailVerified", "createdAt", "updatedAt"
        ) VALUES (
          'existing-user', 'Existing User', 'existing@example.test', 1,
          '2026-07-26T00:00:00.000Z', '2026-07-26T00:00:00.000Z'
        );
      `);

      database.exec(coreSchemaMigration);
      database.exec(coreSchemaMigration);

      expect(database.prepare(`SELECT id, email FROM "user"`).all()).toEqual([
        { id: "existing-user", email: "existing@example.test" },
      ]);
      expect(database.prepare("PRAGMA foreign_key_check").all()).toEqual([]);
    } finally {
      database.close();
    }
  });

  it("fails closed when an existing Better Auth table has an incompatible shape", () => {
    const database = createDatabase();
    try {
      database.exec(rateLimitMigration);
      database.exec(`CREATE TABLE "verification" ("id" TEXT NOT NULL PRIMARY KEY);`);

      expect(() => database.exec(coreSchemaMigration)).toThrow(/CHECK constraint failed|no such column/);
    } finally {
      database.close();
    }
  });

  it("fails closed when a required unique constraint is only composite", () => {
    const database = createDatabase();
    try {
      database.exec(rateLimitMigration);
      database.exec(`
        CREATE TABLE "user" (
          "id" TEXT NOT NULL PRIMARY KEY,
          "name" TEXT NOT NULL,
          "email" TEXT NOT NULL,
          "emailVerified" INTEGER NOT NULL,
          "image" TEXT,
          "createdAt" DATE NOT NULL,
          "updatedAt" DATE NOT NULL,
          UNIQUE ("email", "name")
        );
      `);

      expect(() => database.exec(coreSchemaMigration)).toThrow(/CHECK constraint failed/);
    } finally {
      database.close();
    }
  });

  it("fails closed when a required unique constraint is partial", () => {
    const database = createDatabase();
    try {
      database.exec(rateLimitMigration);
      database.exec(`
        CREATE TABLE "user" (
          "id" TEXT NOT NULL PRIMARY KEY,
          "name" TEXT NOT NULL,
          "email" TEXT NOT NULL,
          "emailVerified" INTEGER NOT NULL,
          "image" TEXT,
          "createdAt" DATE NOT NULL,
          "updatedAt" DATE NOT NULL
        );
        CREATE UNIQUE INDEX "user_email_partial_idx"
          ON "user" ("email") WHERE "emailVerified" = 1;
      `);

      expect(() => database.exec(coreSchemaMigration)).toThrow(/CHECK constraint failed/);
    } finally {
      database.close();
    }
  });

  it("fails closed when a named lookup index has the wrong definition", () => {
    const database = createDatabase();
    try {
      database.exec(rateLimitMigration);
      database.exec(`
        CREATE TABLE "index_collision" ("wrongColumn" TEXT NOT NULL);
        CREATE INDEX "session_userId_idx" ON "index_collision" ("wrongColumn");
      `);

      expect(() => database.exec(coreSchemaMigration)).toThrow(/CHECK constraint failed/);
    } finally {
      database.close();
    }
  });

  it("cascades user-owned sessions and accounts without deleting verification rows", () => {
    const database = createDatabase();
    try {
      applyTrackedSchema(database);
      database.exec(`
        INSERT INTO "user" (
          "id", "name", "email", "emailVerified", "createdAt", "updatedAt"
        ) VALUES (
          'user-1', 'Test User', 'user@example.test', 1,
          '2026-07-26T00:00:00.000Z', '2026-07-26T00:00:00.000Z'
        );
        INSERT INTO "session" (
          "id", "expiresAt", "token", "createdAt", "updatedAt", "userId"
        ) VALUES (
          'session-1', '2026-07-27T00:00:00.000Z', 'test-session-token',
          '2026-07-26T00:00:00.000Z', '2026-07-26T00:00:00.000Z', 'user-1'
        );
        INSERT INTO "account" (
          "id", "accountId", "providerId", "userId", "createdAt", "updatedAt"
        ) VALUES (
          'account-1', 'provider-account-1', 'google', 'user-1',
          '2026-07-26T00:00:00.000Z', '2026-07-26T00:00:00.000Z'
        );
        INSERT INTO "verification" (
          "id", "identifier", "value", "expiresAt", "createdAt", "updatedAt"
        ) VALUES (
          'verification-1', 'oauth-state', 'opaque-test-value',
          '2026-07-27T00:00:00.000Z', '2026-07-26T00:00:00.000Z',
          '2026-07-26T00:00:00.000Z'
        );
        DELETE FROM "user" WHERE "id" = 'user-1';
      `);

      expect(database.prepare(`SELECT COUNT(*) AS count FROM "session"`).get()).toEqual({ count: 0 });
      expect(database.prepare(`SELECT COUNT(*) AS count FROM "account"`).get()).toEqual({ count: 0 });
      expect(database.prepare(`SELECT COUNT(*) AS count FROM "verification"`).get()).toEqual({ count: 1 });
      expect(database.prepare("PRAGMA foreign_key_check").all()).toEqual([]);
    } finally {
      database.close();
    }
  });
});
