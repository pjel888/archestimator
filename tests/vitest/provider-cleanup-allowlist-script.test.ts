import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import {
  buildProviderCleanupAllowlistReport,
  renderProviderCleanupAllowlistMarkdown,
  scanProviderCleanupReferences,
} from "@/../scripts/generate-provider-cleanup-allowlist";

const historicalSupabaseTypesPath = ["src", "lib", "supabase", "types.ts"].join("/");

function writeFixture(root: string, path: string, text: string) {
  const fullPath = join(root, path);
  mkdirSync(fullPath.slice(0, fullPath.lastIndexOf("/")), { recursive: true });
  writeFileSync(fullPath, text);
}

function runCli(env: NodeJS.ProcessEnv) {
  return spawnSync("bun", ["run", "scripts/generate-provider-cleanup-allowlist.ts"], {
    cwd: process.cwd(),
    env: { ...process.env, ...env },
    encoding: "utf8",
    timeout: 30_000,
  });
}

describe("provider cleanup allowlist report script", () => {
  it("classifies scanner, security, negative-assertion, compatibility, type-reference, and cleanup-candidate hits", () => {
    const root = mkdtempSync(join(tmpdir(), "provider-cleanup-allowlist-"));
    writeFixture(root, "src/lib/runtime.ts", "import { createClient } from '@supabase/supabase-js';");
    writeFixture(root, historicalSupabaseTypesPath, "// generated by @supabase/supabase-js");
    writeFixture(root, "scripts/generate-cloudflare-provider-exit-pack.ts", "const key = 'RESEND_API_KEY';");
    writeFixture(root, "tests/vitest/project-invite-entry-route.test.ts", "expect(source).not.toContain('NEXT_PUBLIC_SUPABASE_URL');");
    writeFixture(root, "tests/vitest/redact.test.ts", "redact('SUPABASE_SERVICE_ROLE_KEY=secret');");
    writeFixture(root, "tests/vitest/auth-proxy.test.ts", "vi.mock('@supabase/ssr', () => ({}));");
    writeFixture(root, "tests/vitest/notification-rls-proof.test.ts", "import { createClient } from '@supabase/supabase-js';");
    writeFixture(root, "supabase/migration-evidence/provider-parity-proofs/archived.ts", "import '@supabase/supabase-js';");

    const report = buildProviderCleanupAllowlistReport({
      generatedAt: "2026-07-04T00:00:00.000Z",
      rootDir: root,
      scanPaths: ["src", "scripts", "tests", "supabase"],
    });

    expect(report.scan.totalHitFiles).toBe(7);
    expect(report.scan.unclassifiedFiles).toEqual([]);
    expect(report.scan.dispositionCounts).toMatchObject({
      "active-runtime-blocker": 1,
      "type-reference-retirement": 1,
      "keep-active-audit-tooling": 1,
      "keep-active-negative-assertion": 1,
      "keep-active-security-fixture": 1,
      "compatibility-guard": 1,
      "cleanup-candidate": 1,
    });
    expect(report.readiness.activeRuntimeProviderReferencesReady).toBe(false);
    expect(report.readiness.allProviderStringsClassified).toBe(true);
    expect(report.readiness.providerCleanupAllowlistReady).toBe(false);
    expect(report.blockers).toEqual(expect.arrayContaining([
      expect.stringContaining("Active runtime/source provider references remain"),
      expect.stringContaining("cleanup-candidate"),
    ]));
    expect(report.scan.files.find((file) => file.file === "supabase/migration-evidence/provider-parity-proofs/archived.ts"))
      .toBeUndefined();
  });

  it("keeps active runtime clean when only intentional fixtures and open cleanup candidates remain", () => {
    const root = mkdtempSync(join(tmpdir(), "provider-cleanup-open-candidates-"));
    writeFixture(root, "scripts/generate-cloudflare-provider-exit-pack.ts", "const key = 'RESEND_API_KEY';");
    writeFixture(root, "tests/vitest/project-invite-entry-route.test.ts", "expect(source).not.toContain('NEXT_PUBLIC_SUPABASE_URL');");
    writeFixture(root, "tests/vitest/notification-rls-proof.test.ts", "import { createClient } from '@supabase/supabase-js';");
    writeFixture(root, "tests/vitest/upload-storage-denial-proof.test.ts", "process.env.SUPABASE_SERVICE_ROLE_KEY;");

    const scan = scanProviderCleanupReferences({
      rootDir: root,
      scanPaths: ["scripts", "tests"],
    });
    const report = buildProviderCleanupAllowlistReport({
      generatedAt: "2026-07-04T00:00:00.000Z",
      scan,
    });

    expect(report.scan.unclassifiedFiles).toEqual([]);
    expect(report.readiness.activeRuntimeProviderReferencesReady).toBe(true);
    expect(report.readiness.providerCleanupAllowlistReady).toBe(false);
    expect(report.scan.files.map((file) => file.file)).toEqual(expect.arrayContaining([
      "scripts/generate-cloudflare-provider-exit-pack.ts",
      "tests/vitest/notification-rls-proof.test.ts",
      "tests/vitest/upload-storage-denial-proof.test.ts",
    ]));
    expect(report.scan.files.find((file) => file.file === "tests/vitest/notification-rls-proof.test.ts")?.disposition)
      .toBe("cleanup-candidate");
  });

  it("detects broad Supabase boundary tokens beyond the service-role key", () => {
    const root = mkdtempSync(join(tmpdir(), "provider-cleanup-broad-supabase-"));
    writeFixture(root, "src/lib/runtime.ts", [
      "const url = process.env.SUPABASE_DB_URL;",
      "import { createSupabaseServerClient } from '@/lib/supabase/server';",
      "const rows = supabase.from('projects').select('*');",
    ].join("\n"));
    writeFixture(root, "scripts/linked.ts", [
      "const ref = process.env.SUPABASE_PROJECT_ID;",
      "const command = 'supabase db push --linked --dry-run';",
    ].join("\n"));

    const scan = scanProviderCleanupReferences({
      rootDir: root,
      scanPaths: ["src", "scripts"],
    });
    const tokens = scan.files.flatMap((file) => file.hits.map((hit) => hit.token));

    expect(scan.files.map((file) => file.file)).toEqual([
      "scripts/linked.ts",
      "src/lib/runtime.ts",
    ]);
    expect(tokens).toEqual(expect.arrayContaining([
      "SUPABASE_*",
      "@/lib/supabase",
      "createSupabase*",
      "supabase.*",
      "supabase db",
    ]));
  });

  it("renders and writes sanitized JSON plus Markdown reports", () => {
    const dir = mkdtempSync(join(tmpdir(), "provider-cleanup-allowlist-output-"));
    const outputFile = join(dir, "report.json");
    const markdownFile = join(dir, "report.md");

    const run = runCli({
      OUTPUT_FILE: outputFile,
      MARKDOWN_FILE: markdownFile,
      PROVIDER_CLEANUP_ROOT_DIR: dir,
      PROVIDER_CLEANUP_SCAN_PATHS: ".",
      STRICT_PROVIDER_CLEANUP_EXIT: "0",
    });

    expect(run.status).toBe(0);
    expect(run.stderr).toBe("");

    const report = JSON.parse(readFileSync(outputFile, "utf8"));
    const markdown = readFileSync(markdownFile, "utf8");
    expect(report.mode).toBe("provider-cleanup-allowlist-report");
    expect(markdown).toContain("Provider cleanup allowlist report");
    expect(renderProviderCleanupAllowlistMarkdown(report)).toContain("Provider cleanup allowlist report");
  });

  it("passes strict mode once final cleanup blockers are gone", () => {
    const dir = mkdtempSync(join(tmpdir(), "provider-cleanup-allowlist-strict-"));
    const run = runCli({
      OUTPUT_FILE: join(dir, "strict.json"),
      MARKDOWN_FILE: join(dir, "strict.md"),
      PROVIDER_CLEANUP_ROOT_DIR: dir,
      PROVIDER_CLEANUP_SCAN_PATHS: ".",
      STRICT_PROVIDER_CLEANUP_EXIT: "1",
    });

    expect(run.status).toBe(0);
    expect(run.stderr).toBe("");
    expect(run.stdout).toContain('"strictProviderCleanupExit": true');
    expect(run.stdout).toContain('"finalProviderCleanupReady": true');
    expect(run.stdout).toContain('"exitCode": 0');
  });
});
