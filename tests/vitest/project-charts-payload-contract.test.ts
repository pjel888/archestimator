import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { buildSeriesByEstimate } from "@/lib/project-charts/project-comparison-view";
import type {
  ProjectChartCategoryNodeFact,
  ProjectChartEstimateOption,
  ProjectChartNodeFact,
  ProjectChartRowFact,
  ProjectChartSupplierFact,
} from "@/lib/project-charts/types";
import {
  LARGE_PROJECT_CHARTS_FIXTURE_ROWS,
  PROJECT_CHARTS_PAYLOAD_BUDGET_BYTES,
  buildLargeProjectChartsPayload,
} from "../../scripts/lib/project-charts-payload-fixture";

/**
 * Runtime payload contract (`09` P2.4 / `13` R-2 / `07` A).
 *
 * Proves the charts payload is buckets-only at runtime by building the SAME
 * server-side aggregation the repository uses over a large synthetic fixture
 * (~5,000 row items across two estimates) and asserting the serialized
 * `ProjectChartsData` (a) carries no raw fact arrays, (b) leaks no per-row cost
 * fields, and (c) is well under 50 KB uncompressed.
 *
 * The measured payload artifact is now generated by an explicit command rather
 * than a test side effect:
 *   bun run generate:project-charts-payload-evidence
 * A source check confirms the repository return shape and the data contract match.
 */

describe("project charts payload contract (P2.4 / R-2)", () => {
  const payload = buildLargeProjectChartsPayload();
  const serialized = JSON.stringify(payload);

  it("ships no raw fact arrays in the serialized payload", () => {
    for (const key of ["rowFacts", "nodeFacts", "categoryNodeFacts", "supplierFacts"]) {
      expect(serialized).not.toContain(`"${key}"`);
    }
  });

  it("leaks no per-row cost fields (data minimization, `05` SEC-1)", () => {
    for (const field of ["unitCost", "quantity", "miscCost", "contingencyPercentage", "sourceSupplierId"]) {
      expect(serialized).not.toContain(`"${field}"`);
    }
    // No per-row id leaked (buckets, not rows).
    expect(serialized).not.toContain('"row-0"');
  });

  it(`is under ${PROJECT_CHARTS_PAYLOAD_BUDGET_BYTES} bytes uncompressed on a ~${LARGE_PROJECT_CHARTS_FIXTURE_ROWS}-row fixture`, () => {
    const bytes = Buffer.byteLength(serialized, "utf8");
    expect(bytes).toBeLessThan(PROJECT_CHARTS_PAYLOAD_BUDGET_BYTES);
  });

  it("matches the repository return shape and the data contract (source cross-check)", () => {
    const repositorySource = readFileSync(join(process.cwd(), "src/lib/repositories/project-charts-repository.ts"), "utf8");
    const typesSource = readFileSync(join(process.cwd(), "src/lib/project-charts/types.ts"), "utf8");
    // Repository returns the aggregated series, not raw facts.
    expect(repositorySource).toContain("seriesByEstimateId");
    expect(repositorySource).toContain("buildSeriesByEstimate");
    // The data contract no longer carries raw fact arrays.
    expect(typesSource).not.toMatch(/rowFacts:\s*ProjectChartRowFact\[\]/);
    expect(typesSource).not.toMatch(/supplierFacts:\s*ProjectChartSupplierFact\[\]/);
  });
});

describe("project charts global taxonomy invariant (`02` DB-1)", () => {
  it("builds category buckets from the global component_category_nodes taxonomy without workspace/project filtering", () => {
    // Simulate two estimates belonging to different workspaces/projects.
    const estimateA: ProjectChartEstimateOption = {
      id: "ws-a-proj-1-estimate",
      name: "Workspace A Estimate",
      sheetCode: "EST-A",
      currencyCode: "PHP",
      updatedAt: "2026-05-02T00:00:00Z",
      rowCount: 0,
      totalCost: 0,
    };
    const estimateB: ProjectChartEstimateOption = {
      id: "ws-b-proj-2-estimate",
      name: "Workspace B Estimate",
      sheetCode: "EST-B",
      currencyCode: "PHP",
      updatedAt: "2026-05-01T00:00:00Z",
      rowCount: 0,
      totalCost: 0,
    };

    // Global taxonomy nodes — the same ids would be shared across all workspaces.
    const globalCategories: ProjectChartCategoryNodeFact[] = [
      { id: "global-cat-concrete", parentId: null, nodeType: "category", label: "Concrete", sortOrder: 0 },
      { id: "global-cat-steel", parentId: null, nodeType: "category", label: "Steel", sortOrder: 1 },
    ];

    const nodes: ProjectChartNodeFact[] = [
      { id: "node-a-1", estimateId: estimateA.id, parentId: null, kind: "Area", name: "Area A1", sortOrder: 0 },
      { id: "node-b-1", estimateId: estimateB.id, parentId: null, kind: "Area", name: "Area B1", sortOrder: 0 },
    ];

    const suppliers: ProjectChartSupplierFact[] = [
      { id: "supplier-a", name: "Supplier A", normalizedName: "supplier-a", sortOrder: 0 },
      { id: "supplier-b", name: "Supplier B", normalizedName: "supplier-b", sortOrder: 1 },
    ];

    const rows: ProjectChartRowFact[] = [
      {
        id: "row-a-concrete",
        estimateId: estimateA.id,
        nodeId: "node-a-1",
        categoryNodeId: "global-cat-concrete",
        supplierId: "supplier-a",
        supplierName: null,
        sourceSupplierId: null,
        sourceSupplierName: null,
        quantity: 10,
        unitCost: 100,
        miscCost: 0,
      },
      {
        id: "row-b-steel",
        estimateId: estimateB.id,
        nodeId: "node-b-1",
        categoryNodeId: "global-cat-steel",
        supplierId: "supplier-b",
        supplierName: null,
        sourceSupplierId: null,
        sourceSupplierName: null,
        quantity: 5,
        unitCost: 200,
        miscCost: 0,
      },
    ];

    const seriesByEstimateId = buildSeriesByEstimate(
      {
        estimates: [estimateA, estimateB],
        rows,
        nodes,
        categoryNodes: globalCategories,
        suppliers,
      },
      [estimateA.id, estimateB.id],
    );

    const categoryBucketsA = seriesByEstimateId[estimateA.id]?.category.allBuckets ?? [];
    const categoryBucketsB = seriesByEstimateId[estimateB.id]?.category.allBuckets ?? [];

    // Each estimate should resolve its row against the same global category ids,
    // proving the taxonomy is not scoped or filtered by workspace/project.
    expect(categoryBucketsA.map((bucket) => bucket.id)).toContain("global-cat-concrete");
    expect(categoryBucketsB.map((bucket) => bucket.id)).toContain("global-cat-steel");

    // Labels come from the global taxonomy, not from estimate/workspace context.
    expect(categoryBucketsA.find((bucket) => bucket.id === "global-cat-concrete")?.label).toBe("Concrete");
    expect(categoryBucketsB.find((bucket) => bucket.id === "global-cat-steel")?.label).toBe("Steel");

    // No workspace/project identifiers should leak into category bucket ids.
    for (const bucket of [...categoryBucketsA, ...categoryBucketsB]) {
      expect(bucket.id).not.toContain("ws-a");
      expect(bucket.id).not.toContain("ws-b");
      expect(bucket.id).not.toContain("proj-1");
      expect(bucket.id).not.toContain("proj-2");
      expect(bucket.id).not.toContain("estimate");
    }
  });
});

describe("project chart composition aggregate", () => {
  it("ships direct, misc, and adjustment totals as a reconciled aggregate, not row facts", () => {
    const estimateA: ProjectChartEstimateOption = {
      id: "estimate-a",
      name: "Estimate A",
      sheetCode: "EST-A",
      currencyCode: "PHP",
      updatedAt: null,
      rowCount: 0,
      totalCost: 0,
    };
    const rows: ProjectChartRowFact[] = [
      row("row-a", estimateA.id, 2, 100, 10, 5),
      row("row-b", estimateA.id, 1, 50, 20, 10),
    ];

    const seriesByEstimateId = buildSeriesByEstimate(
      {
        estimates: [estimateA],
        rows,
        nodes: [],
        categoryNodes: [],
        suppliers: [],
      },
      [estimateA.id],
    );

    const estimateSeries = seriesByEstimateId[estimateA.id] as unknown as {
      composition?: { baseTotal: number; miscTotal: number; adjustmentTotal: number; grandTotal: number };
      category: { total: number };
    };

    expect(estimateSeries.composition).toEqual({
      baseTotal: 250,
      miscTotal: 30,
      adjustmentTotal: 15,
      grandTotal: 295,
    });
    expect(estimateSeries.composition?.grandTotal).toBe(estimateSeries.category.total);

    const serialized = JSON.stringify(seriesByEstimateId);
    for (const field of ["unitCost", "quantity", "miscCost", "contingencyPercentage", "sourceSupplierId"]) {
      expect(serialized).not.toContain(`"${field}"`);
    }
  });
});

function row(
  id: string,
  estimateId: string,
  quantity: number,
  unitCost: number,
  miscCost: number,
  contingencyPercentage: number,
): ProjectChartRowFact {
  return {
    id,
    estimateId,
    nodeId: null,
    categoryNodeId: null,
    supplierId: null,
    supplierName: null,
    sourceSupplierId: null,
    sourceSupplierName: null,
    quantity,
    unitCost,
    miscCost,
    contingencyPercentage,
  };
}
