import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const dashboardClient = readFileSync("src/components/workshop/ProjectDashboardClient.tsx", "utf8");
const mapComponent = readFileSync("src/components/workshop/ProjectLocationMap.tsx", "utf8");
const mapStyle = readFileSync("src/lib/google-maps/project-location-map-style.ts", "utf8");
const addressAutocomplete = readFileSync("src/components/workshop/ProjectAddressAutocomplete.tsx", "utf8");
const googleMapsLoader = readFileSync("src/lib/google-maps/loader.ts", "utf8");
const rootLayout = readFileSync("src/app/layout.tsx", "utf8");
const packageJson = readFileSync("package.json", "utf8");

describe("project location map source boundaries", () => {
  it("keeps Google Maps loading behind the dedicated client components", () => {
    expect(dashboardClient).not.toContain("dynamic(");
    expect(dashboardClient).not.toContain('import("./ProjectLocationMap")');
    expect(dashboardClient).not.toContain("ssr: false");
    expect(dashboardClient).not.toMatch(/from\s+["']maplibre-gl/);
    expect(dashboardClient).not.toMatch(/from\s+["']leaflet/);
    expect(mapComponent).toContain("loadGoogleMapsApi");
    expect(mapComponent).toContain('importLibrary("maps")');
    expect(mapComponent).not.toContain('importLibrary("marker")');
    expect(mapComponent).toContain('data-testid="project-location-map-pin"');
    expect(mapComponent).toContain('data-testid="project-location-overlay-grid"');
    expect(mapComponent).toContain('data-testid="project-location-frosted-upper-panel"');
    expect(mapComponent).toContain('data-testid="project-location-frosted-panel"');
    expect(mapComponent).toContain('data-testid="project-location-frosted-lower-left-panel"');
    expect(mapComponent).toContain('data-testid="project-location-frosted-lower-left-fill-panel"');
    expect(mapComponent).toContain("lowerLeftDetail");
    expect(mapComponent).toContain("grid-cols-16");
    expect(mapComponent).toContain("grid-rows-8");
    expect(mapComponent).toContain("gap-2");
    expect(mapComponent).toContain("p-2");
    expect(mapComponent).toContain("col-start-1");
    expect(mapComponent).toContain("col-span-5");
    expect(mapComponent).toContain("row-span-4");
    expect(mapComponent).toContain("col-start-13");
    expect(mapComponent).toContain("col-span-4");
    expect(mapComponent).toContain("row-start-5");
    expect(mapComponent).toContain("row-span-1");
    expect(mapComponent).toContain("col-span-5 col-start-1 row-span-3 row-start-6");
    expect(mapComponent).toContain("overflow-hidden p-2");
    expect(mapComponent).toContain("row-start-6");
    expect(mapComponent).toContain("row-span-3");
    expect(mapComponent).toContain("PROJECT_LOCATION_MAP_STYLES");
    expect(mapStyle).toContain('featureType: "poi"');
    expect(mapStyle).toContain('featureType: "administrative.locality"');
    expect(mapStyle).toContain('featureType: "administrative.neighborhood"');
    expect(mapStyle).toContain('featureType: "road"');
    expect(mapStyle).toContain('featureType: "water"');
    expect(mapStyle).toContain("#dcebf2");
    expect(mapStyle).toContain("#f4f4f4");
    expect(mapStyle).toContain('elementType: "labels.icon"');
    expect(mapComponent).not.toContain("mapId: mapId");
    expect(addressAutocomplete).toContain("loadGoogleMapsApi");
    expect(addressAutocomplete).toContain('importLibrary("places")');
    expect(addressAutocomplete).toContain("DropdownPopupPanel");
    expect(addressAutocomplete).toContain("PROJECT_ADDRESS_AUTOCOMPLETE_TYPES");
    expect(addressAutocomplete).toContain("includedPrimaryTypes");
    expect(addressAutocomplete).toContain('role={canUseGooglePlaces ? "combobox" : undefined}');
    expect(addressAutocomplete).toContain('role="listbox"');
    expect(dashboardClient).toContain("PROJECT_METADATA_INPUT_CLASS");
    expect(dashboardClient).toContain("hover:bg-white/35");
    expect(dashboardClient).toContain("focus:bg-white/85");
    expect(googleMapsLoader).toContain("maps.googleapis.com/maps/api/js");
    expect(rootLayout).not.toContain("maplibre-gl");
    expect(packageJson).not.toContain('"maplibre-gl"');
  });

  it("uses Google Places for autocomplete and avoids legacy public map/geocoding providers", () => {
    expect(addressAutocomplete).toContain("AutocompleteSuggestion.fetchAutocompleteSuggestions");
    expect(addressAutocomplete).toContain('fields: ["id", "displayName", "formattedAddress", "location"]');
    expect(dashboardClient).toContain("saveProjectLocation");
    expect(dashboardClient).toContain('formData.set("geocoderName", "google")');
    expect(dashboardClient).toContain('formData.set("providerPlaceId"');
    const combinedSource = `${dashboardClient}\n${mapComponent}\n${mapStyle}\n${addressAutocomplete}\n${googleMapsLoader}`;
    expect(combinedSource).not.toContain("Nominatim");
    expect(combinedSource).not.toContain("nominatim");
    expect(combinedSource).not.toContain("tile.openstreetmap.org");
    expect(combinedSource).not.toContain("tiles.openfreemap.org");
    expect(combinedSource).not.toContain("Mapbox");
  });
});
